# A port is handed out once, so two QEMUs started side by side never get the
# same forward.
PORTS = set()
PORTS_LOCK = threading.Lock()


def free_port():
    with PORTS_LOCK:
        while True:
            with socket.socket() as s:
                s.bind(('127.0.0.1', 0))
                port = s.getsockname()[1]
            if port not in PORTS:
                PORTS.add(port)
                return port


def qemu_base(machine, flash, efuse):
    t = QEMU_TARGETS[machine]
    args = [t.qemu_prog] + t.qemu_args.split()
    if flash is not None:
        args += ['-drive', f'file={flash},if=mtd,format=raw']
    return args + [
        '-drive', f'file={efuse},if=none,format=raw,id=efuse',
        '-global', f'driver=nvram.{machine}.efuse,property=drive,value=efuse',
        '-global', f'driver=timer.{machine}.timg,property=wdt_disable,value=true',
        '-nographic',
    ]


# Every QEMU not yet stopped. A `finally` does not run when the default
# SIGTERM ends this process (the job cancelled, make killed), and a QEMU left
# running holds the job container's cleanup, so a signal kills what is here.
LIVE = set()
LIVE_LOCK = threading.Lock()


def reap(signum, _frame):
    with LIVE_LOCK:
        procs = list(LIVE)
    for p in procs:
        if p.poll() is None:
            p.kill()
    os._exit(128 + signum)


class Qemu:
    """One QEMU process, its serial console appended to a log file."""

    def __init__(self, args, logpath):
        self.logpath = logpath
        self.logfile = open(logpath, 'ab')
        self.proc = subprocess.Popen(args, stdin=subprocess.DEVNULL,
                                     stdout=self.logfile, stderr=subprocess.STDOUT)
        with LIVE_LOCK:
            LIVE.add(self.proc)

    def text(self):
        return Path(self.logpath).read_text(errors='replace')

    def wait_for(self, pattern, count=1, timeout=BOOT_TIMEOUT):
        """Until the log holds `pattern` `count` times; bounded by `timeout`,
        and by QEMU exiting, which is what the log is read between."""
        deadline = time.time() + timeout
        while time.time() < deadline:
            if len(re.findall(pattern, self.text())) >= count:
                return
            # Between reads of the log, wait on the one other thing that can
            # happen: QEMU exiting.
            try:
                self.proc.wait(min(0.25, max(0, deadline - time.time())))
            except subprocess.TimeoutExpired:
                continue
            raise Failure(f'QEMU exited ({self.proc.returncode}) waiting for {pattern!r}')
        raise Failure(f'{timeout}s without {pattern!r} (x{count}) in {self.logpath}')

    def stop(self):
        if self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(10)
            except subprocess.TimeoutExpired:
                self.proc.kill()
                self.proc.wait()
        with LIVE_LOCK:
            LIVE.discard(self.proc)
        self.logfile.close()


def run(args, logpath, **kw):
    with open(logpath, 'ab') as f:
        f.write(f'$ {" ".join(map(str, args))}\n'.encode())
        f.flush()
        r = subprocess.run(list(map(str, args)), stdout=f, stderr=subprocess.STDOUT, **kw)
    return r.returncode


# --------------------------------------------------------------- the keys

def deviceid_fingerprint(pub):
    """What the app logs: the first 16 bytes of SHA-256 over the point x||y."""
    return hashlib.sha256(pub).hexdigest()[:32]


P256_N = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551


def deviceid_point(uds):
    """The DeviceID point x||y of a UDS, derived as src/crypto/deviceid_p256.c
    does -- seed HMAC-SHA256(UDS, label), rehashed until it is in [1, n-1] --
    by Python's own P-256."""
    d = hmac.new(uds, b'tfw-deviceid-v1', hashlib.sha256).digest()
    while not 0 < int.from_bytes(d, 'big') < P256_N:
        d = hashlib.sha256(d).digest()
    pub = ec.derive_private_key(int.from_bytes(d, 'big'), ec.SECP256R1()).public_key().public_numbers()
    return pub.x.to_bytes(32, 'big') + pub.y.to_bytes(32, 'big')


def cdi_fingerprint(uds, measurement):
    """What the app logs: HMAC(CDI, label) of CDI = HMAC-SHA256(UDS, measurement)."""
    cdi = hmac.new(uds, measurement, hashlib.sha256).digest()
    return hmac.new(cdi, b'tfw-cdi-fingerprint-v1', hashlib.sha256).hexdigest()[:32]


# -------------------------------------------------------------- the flash

def partitions(table):
    """label -> (offset, size) from an ESP-IDF binary partition table."""
    out = {}
    for i in range(0, len(table), 32):
        e = table[i:i + 32]
        if e[:2] != b'\xaa\x50':
            break
        _, _, _, off, size, label, _ = struct.unpack('<2sBBII16sI', e)
        out[label.rstrip(b'\0').decode()] = (off, size)
    return out


def make_flash(out, machine, path):
    idf = out / 'idf'
    flash = bytearray(b'\xff' * FLASH_SIZE)

    def place(off, data):
        flash[off:off + len(data)] = data

    place(MACHINES[machine]['bootloader'], (idf / 'bootloader' / 'bootloader.bin').read_bytes())
    table = (idf / 'partition_table' / 'partition-table.bin').read_bytes()
    place(0x10000, table)
    parts = partitions(table)
    place(parts['otadata'][0], (idf / 'ota_data_initial.bin').read_bytes())
    place(parts['ota_0'][0], (out / 'trusted-firmware.bin').read_bytes())
    place(parts['tfw_plat'][0], (out / 'tfw_plat.bin').read_bytes())
    path.write_bytes(flash)
    return parts


# --------------------------------------------------------------- the eFuses

@contextlib.contextmanager
def download_mode(machine, efuse, logpath):
    """QEMU in ROM download mode on `efuse`; yields espefuse's command line."""
    port = free_port()
    args = qemu_base(machine, None, efuse) + QEMU_TARGETS[machine].boot_mode_arg.split() + [
        '-serial', f'tcp:127.0.0.1:{port},server,nowait']
    q = Qemu(args, logpath)
    try:
        deadline = time.time() + 20
        while True:
            try:
                socket.create_connection(('127.0.0.1', port), 1).close()
                break
            except OSError:
                if time.time() > deadline:
                    raise Failure('QEMU download mode never opened its serial port')
                try:
                    q.proc.wait(0.2)
                except subprocess.TimeoutExpired:
                    continue
                raise Failure(f'QEMU exited ({q.proc.returncode}) before opening its serial port')
        yield ['espefuse.py', '--chip', machine, '--port', f'socket://127.0.0.1:{port}',
               '--before', 'no_reset', '--do-not-confirm']
    finally:
        q.stop()


def provision_efuses(work, machine, sign_key, logpath, efuse, uds):
    efuse.write_bytes(QEMU_TARGETS[machine].default_efuse)
    with download_mode(machine, efuse, logpath) as espefuse:
        if machine == 'esp32':
            burn = ['burn_key_digest', sign_key, 'burn_efuse', 'ABS_DONE_1', '1']
        else:
            burn = ['burn_key_digest', 'BLOCK_KEY0', sign_key, 'SECURE_BOOT_DIGEST0']
            if uds:
                burn += ['burn_key', 'BLOCK_KEY1', work / 'uds.bin', 'HMAC_UP']
            burn += ['burn_efuse', 'SECURE_BOOT_EN', '1']
        if run(espefuse + burn, logpath) != 0:
            raise Failure(f'espefuse refused the burn, see {logpath}')
        summary = work / (efuse.stem + '-summary.txt')
        if run(espefuse + ['summary'], summary) != 0:
            raise Failure(f'espefuse summary failed, see {summary}')
        flag = 'ABS_DONE_1' if machine == 'esp32' else 'SECURE_BOOT_EN'
        if not re.search(rf'^{flag} .*= True', summary.read_text(), re.M):
            raise Failure(f'{flag} is not set after the burn, see {summary}')
    return efuse


# QEMU's eFuse file is its ESPEfuseBlocks, little-endian words from offset 0
# (Espressif QEMU esp-develop-9.2.2-20260417, hw/nvram/esp_efuse.c:134 and
# include/hw/nvram/esp_efuse.h:71-166): BLOCK0 and BLOCK1 six words each, then
# 8-word blocks, so BLOCK_KEYn starts at word 28 + 8n. espefuse --virt is no
# reader of it: its emulator keeps the register map bit-reversed
# (esptool v4.12.0 espefuse/efuse/emulate_efuse_controller_base.py:58).
EFUSE_KEY_PURPOSE_HMAC_UP = 8      # esptool v4.12.0 espefuse/efuse/esp32c3/fields.py:404


def efuse_keys(efuse):
    """(purpose, read-protected, key write-protected, purpose write-protected,
    the 32 bytes) of BLOCK_KEY0..5 in a QEMU eFuse file."""
    w = struct.unpack_from('<84I', efuse.read_bytes())
    wr_dis, rd_dis = w[0], w[1] & 0x7f                         # esp_efuse.h:72, :238
    purposes = [(w[2] >> 24) & 0xf, w[2] >> 28] + [(w[3] >> (4 * n)) & 0xf for n in range(4)]  # esp_efuse.h:241-249
    return [(purposes[n], bool(rd_dis >> n & 1),               # esp_efuse.c:105-119, BLOCK4 is bit 0
             bool(wr_dis >> (23 + n) & 1),                     # esp_efuse.c:220-221, BLOCKk is bit 19+k
             bool(wr_dis >> (8 + n) & 1),                      # esp_efuse.c:173-178, KEY_PURP_n is bit 8+n
             struct.pack('<8I', *w[28 + 8 * n:36 + 8 * n]))
            for n in range(6)]


def read_back(machine, efuse, logpath, point):
    """The UDS where a host could look for it. Over the ROM's download port:
    nothing, because secure boot left the ROM in Secure Download Mode and
    espefuse refuses to read. In the eFuses themselves, read offline from QEMU's
    file once QEMU has exited: one HMAC_UP key, read-protected so the chip
    blanks it to software, write-protected with its purpose, and holding the
    key that derives `point` -- the burn the device answered for."""
    try:
        with download_mode(machine, efuse, logpath) as espefuse:
            rc = run(espefuse + ['summary'], logpath, timeout=120)
    except subprocess.TimeoutExpired:
        raise Failure(f'espefuse summary did not finish in 120s, see {logpath}')
    # esptool v4.12.0: espefuse/efuse/esp32c3/fields.py:83-88 raises, and
    # espefuse/__init__.py:362-367 prints it and exits 2.
    expect(rc != 0 and 'Secure Download Mode is enabled. The tool can not read eFuses.'
           in Path(logpath).read_text(errors='replace'),
           'read back: the ROM is in Secure Download Mode; espefuse cannot read the eFuses over the port')
    keys = [k for k in efuse_keys(efuse) if k[0] == EFUSE_KEY_PURPOSE_HMAC_UP]
    expect(len(keys) == 1, 'read back offline: one HMAC_UP key block in the eFuses')
    _, rd, wr, wr_purpose, key = keys[0]
    expect(rd and wr and wr_purpose,
           'read back offline: the HMAC_UP block is read-protected, and it and its purpose write-protected')
    # Byte order as esp_efuse_write_key left it, either way round: what is held
    # to the point is that this key, and no other, is the one the device used.
    expect(point in (deviceid_point(key), deviceid_point(key[::-1])),
           'read back offline: the burned key derives the point PROV_GENKEY returned')


# ----------------------------------------------------------------- a boot

def boot(machine, flash, efuse, logpath):
    port = free_port()
    args = qemu_base(machine, flash, efuse) + [
        '-nic', f'user,model=open_eth,hostfwd=tcp:127.0.0.1:{port}-:{WIRE_PORT}']
    return Qemu(args, logpath), port


def wirecheck(binary, port, logpath, *extra, wait=BOOT_TIMEOUT):
    """An OTA stream's cost goes into the job's log as well as its own: the
    command count and stream time wirecheck printed in this call's part of
    logpath, and the call's wall time."""
    logpath = Path(logpath)
    seen = logpath.stat().st_size if logpath.exists() else 0
    start = time.monotonic()
    rc = run([binary, '-addr', f'127.0.0.1:{port}', '-wait', f'{wait}s',
              '-board', str(BOARD_ID)] + list(extra), logpath)
    if '-ota' in extra:
        with open(logpath, 'rb') as f:
            f.seek(seen)
            mine = f.read().decode(errors='replace')
        took = re.findall(r'^wirecheck: ota: (\d+ commands in \S+)$', mine, re.M)
        log(f'  ota {logpath.name}: {took[-1] if took else "no stream time (refused or failed)"}, '
            f'wirecheck {time.monotonic() - start:.0f} s')
    return rc


def ota(image):
    """wirecheck's arguments to stream `image` over OTA: the one place an OTA
    stream's bound is set. wirecheck's -timeout bounds each command; OTA_END
    reads and checks the whole image, so its bound grows with the length at
    OTA_FLOOR_BPS on top of OTA_TIMEOUT. No wait is shortened by a fast host."""
    bound = OTA_TIMEOUT + -(-Path(image).stat().st_size // OTA_FLOOR_BPS)
    return ('-timeout', f'{bound}s', '-ota', image)


def boot_facts(text):
    """The per-boot lines, in boot order."""
    return {
        'measurement': re.findall(r'tfw-l0: app at 0x[0-9a-f]+ verified, measurement ([0-9a-f]{64})', text),
        'cdi': re.findall(r'tfw-id: cdi hmac-fingerprint=([0-9a-f]{32})', text),
        'deviceid': re.findall(r'tfw-id: deviceid p256 sha256\(x\|\|y\)=([0-9a-f]{32}) from eFuse BLOCK\d+', text),
        'wire': re.findall(r'tfw-eth: link up, address \S+, wire on tcp/(\d+)', text),
    }


def tail(path, n=40):
    """The last n lines of a log, for a failure message."""
    try:
        lines = Path(path).read_text(errors='replace').splitlines()
    except FileNotFoundError:
        return f'--- {path}: not written'
    return '\n'.join([f'--- the last {min(n, len(lines))} lines of {path}'] + lines[-n:])


def expect(cond, what, logs=()):
    """A failed check raises with what, and the tail of each of logs after it."""
    if not cond:
        raise Failure('\n'.join([what] + [tail(p) for p in logs]))
    log(f'  ok  {what}')


def provisioning(prov, machine, sign_key, wc, work, out):
    """Step 11: the PROVISION=1 image burns a UDS of its own drawing, and the
    normal image boots with the DeviceID it returned."""
    expect(deviceid_point(UDS) == DEVICEID_PUB,
           'prov: the harness derivation gives the pinned point for the fixed UDS')
    efuse = provision_efuses(work, machine, sign_key, work / 'provision-prov.log', work / 'efuse-prov.bin', uds=False)
    log('  ok  prov: fresh eFuses burned: secure boot v2 key digest and enable, no UDS')
    make_flash(prov, machine, work / 'flash-prov.bin')
    pointfile = work / 'deviceid-prov.hex'
    wlog = work / 'wirecheck-prov.log'
    q, port = boot(machine, work / 'flash-prov.bin', efuse, work / 'boot-prov.log')
    try:
        q.wait_for(r'tfw-eth: link up')
        expect(wirecheck(wc, port, wlog, '-genkey', pointfile) == 0,
               'prov boot: PROV_GENKEY returned a P-256 point, PROV_PUBKEY agrees, a second PROV_GENKEY refused')
        q.wait_for(r'tfw-prov: prov: UDS burned into eFuse BLOCK\d+, read- and write-protected')
    finally:
        q.stop()
    point = bytes.fromhex(pointfile.read_text())
    expect(point != DEVICEID_PUB, 'prov: the point is not the fixed UDS\'s: the part drew its own')
    read_back(machine, efuse, work / 'readback.log', point)
    make_flash(out, machine, work / 'flash-after-prov.bin')
    q, port = boot(machine, work / 'flash-after-prov.bin', efuse, work / 'boot-after-prov.log')
    try:
        q.wait_for(r'tfw-eth: link up')
        expect(wirecheck(wc, port, wlog, '-tier', str(TIER_SECURE_ELEMENT), '-deviceid', point.hex()) == 0,
               'normal boot after provisioning: ATTEST ES256 verified under the point PROV_GENKEY returned')
    finally:
        q.stop()
    facts = boot_facts((work / 'boot-after-prov.log').read_text(errors='replace'))
    expect(facts['deviceid'] == [deviceid_fingerprint(point)],
           f'normal boot after provisioning: DeviceID p256 {deviceid_fingerprint(point)}, the point PROV_GENKEY returned')


def refused(machine, flash, efuse, wc, wlog, logpath, pattern):
    """Boot `flash`; layer 0 must log `pattern` and hand nothing on."""
    q, port = boot(machine, flash, efuse, logpath)
    try:
        q.wait_for(pattern, timeout=BOOT_TIMEOUT)
        no_wire = wirecheck(wc, port, wlog, wait=15) != 0
    finally:
        q.stop()
    text = logpath.read_text(errors='replace')
    facts = boot_facts(text)
    return text, no_wire and not facts['measurement'] and not facts['wire']


def with_app(work, base_flash, app, image, name):
    """The flash with ota_0's image replaced."""
    flash = bytearray(base_flash)
    size = partitions(bytes(flash[0x10000:0x10c00]))['ota_0'][1]
    flash[app:app + size] = b'\xff' * size
    flash[app:app + len(image)] = image
    path = work / f'flash-{name}.bin'
    path.write_bytes(flash)
    return path


def release(unsealed, secure_version, version, image_key, sign_key, suit_emit, out):
    """The app as a later release: its esp_app_desc_t secure_version set (the
    build's CONFIG_BOOTLOADER_APP_SECURE_VERSION), the XOR checksum and the
    appended SHA-256 fixed up, then sealed with trailer `version` and the SUIT
    envelope of sequence `version`."""
    img = bytearray(unsealed)
    magic, old = struct.unpack_from('<II', img, APP_DESC)
    if magic != APP_DESC_MAGIC:
        raise Failure(f'no esp_app_desc_t at {APP_DESC}: magic {magic:#010x}')
    _, digest = l0_seal.layout(img)
    if secure_version is not None:
        struct.pack_into('<I', img, APP_DESC + 4, secure_version)
        for a, b in zip(struct.pack('<I', old), struct.pack('<I', secure_version)):
            img[digest - 1] ^= a ^ b
        img[digest:digest + 32] = hashlib.sha256(img[:digest]).digest()
    l0_seal.seal(bytes(img), BOARD_ID, version, image_key, sign_key, out, suit_emit)
    return out


INFO = re.compile(r'^ota: slot (\d) state (\d+) version (\d+) floor (\d+) flags 0x([0-9a-f]{2}) '
                  r'measurement ([0-9a-f]{64})$', re.M)


def ota_info(wc, port, logpath, *extra, logs=()):
    """wirecheck `extra` then OTA_INFO, into a log of its own: the running
    slot's (state, version, floor, flags, measurement)."""
    if wirecheck(wc, port, logpath, '-timeout', f'{OTA_TIMEOUT}s', *extra, '-info') != 0:
        raise Failure('\n'.join([f'wirecheck {" ".join(map(str, extra))} -info failed']
                                + [tail(p) for p in (logpath,) + tuple(logs)]))
    running = [m for m in INFO.findall(logpath.read_text(errors='replace')) if m[0] == '0']
    if not running:
        raise Failure('\n'.join(['no OTA_INFO line for the running slot', tail(logpath)]))
    _, st, version, floor, flags, m = running[-1]
    return int(st), int(version), int(floor), int(flags, 16), m


def copy(src, dst):
    shutil.copyfile(src, dst)
    return dst


def main():
    out, machine, wc = Path(sys.argv[1]).resolve(), sys.argv[2], Path(sys.argv[3]).resolve()
    suit_emit = Path(sys.argv[4]).resolve()
    prov = Path(sys.argv[5]).resolve() if len(sys.argv) > 5 else None
    if machine not in MACHINES:
        raise Failure(f'machine {machine}: not one of {", ".join(MACHINES)}')
    identity = MACHINES[machine]['identity']
    anti_rollback = MACHINES[machine]['anti_rollback']
    if prov and not identity:
        raise Failure(f'machine {machine}: no UDS to provision (none tier)')
    idf = out / 'idf'
    sign_key = (out.parent / 'keys' / 'secure_boot_signing_key.pem').resolve()
    work = out / 'qemu'
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    log(f'{machine}: {out.name}, logs in {work}')

    sealed = out / 'trusted-firmware.bin'
    measurement = LoadFirmwareImage(machine, str(sealed)).stored_digest
    if identity:
        (work / 'uds.bin').write_bytes(UDS)
    make_flash(out, machine, work / 'flash.bin')
    efuse = provision_efuses(work, machine, sign_key, work / 'provision.log', work / 'efuse.bin', identity)
    log('  ok  eFuses burned: secure boot v2 key digest and enable'
        + (', UDS (HMAC_UP)' if identity else ''))

    # wirecheck holds ATTEST to the tier CAPS reports: with -deviceid on the
    # hmac-p256 tier, a refusal on the none tier.
    tier = TIER_SECURE_ELEMENT if identity else TIER_NONE
    attest = ['-deviceid', DEVICEID_PUB.hex()] if identity else []
    mark = 'tfw-' + os.urandom(2).hex()      # EEPROM_WRITE takes up to 8 bytes
    wlog = work / 'wirecheck.log'
    link = r'tfw-eth: link up'

    # Boot 1, then the soft reset it ends with: boot 2 in the same QEMU.
    q, port = boot(machine, work / 'flash.bin', efuse, work / 'boot-1-2.log')
    try:
        q.wait_for(link)
        expect(wirecheck(wc, port, wlog, '-tier', str(tier), *attest, '-mark', mark, '-reset') == 0,
               'boot 1: PING, CAPS (board 0x81, tier %d), SYSINFO, %s over Ethernet; mark written; soft reset'
               % (tier, 'ATTEST ES256 verified under the pinned DeviceID' if identity else 'ATTEST refused'))
        q.wait_for(link, count=2)
        expect(wirecheck(wc, port, wlog, '-tier', str(tier), *attest, '-expect-mark', mark) == 0,
               'boot 2 (soft reset): the wire, ATTEST, and the EEPROM mark kept')
    finally:
        q.stop()
    # Boot 3: a new QEMU on the same flash and eFuses.
    q, port = boot(machine, work / 'flash.bin', efuse, work / 'boot-3.log')
    try:
        q.wait_for(link)
        expect(wirecheck(wc, port, wlog, '-tier', str(tier), *attest, '-expect-mark', mark) == 0,
               'boot 3 (cold): the wire, ATTEST, and the EEPROM mark kept')
    finally:
        q.stop()

    text = (work / 'boot-1-2.log').read_text(errors='replace') + (work / 'boot-3.log').read_text(errors='replace')
    facts = boot_facts(text)
    expect(facts['measurement'] == [measurement.hex()] * 3,
           f'3 boots: secure boot v2 verified the app; measurement {measurement.hex()[:16]}... is the image SHA-256')
    if identity:
        want_cdi = cdi_fingerprint(UDS, measurement)
        expect(facts['cdi'] == [want_cdi] * 3,
               f'3 boots: CDI fingerprint {want_cdi}, HMAC_UP over the measurement, same every boot')
        want_id = deviceid_fingerprint(DEVICEID_PUB)
        expect(facts['deviceid'] == [want_id] * 3,
               f'3 boots: DeviceID p256 {want_id}, the pinned point of the UDS, same every boot')
    else:
        expect(not facts['cdi'] and not facts['deviceid'],
               'no CDI and no DeviceID on a part with no HMAC peripheral (none tier)')

    # 4: a tampered image, tampered the way an attacker would: one byte of code
    # flipped, and the image's checksum and appended SHA-256 both fixed up to
    # match, so the only thing left to notice is the RSA signature.
    tampered = work / 'flash-tampered.bin'
    flash = bytearray((work / 'flash.bin').read_bytes())
    app = partitions(bytes(flash[0x10000:0x10c00]))['ota_0'][0]
    hashed = LoadFirmwareImage(machine, str(sealed)).data_length
    flash[app + 0x1000] ^= 0x01                  # inside segment 0's data
    flash[app + hashed - 1] ^= 0x01              # the XOR checksum, last byte before the digest
    flash[app + hashed:app + hashed + 32] = hashlib.sha256(flash[app:app + hashed]).digest()
    tampered.write_bytes(flash)
    q, port = boot(machine, tampered, efuse, work / 'boot-tampered.log')
    try:
        q.wait_for(r'tfw-l0: app at 0x[0-9a-f]+ failed verification', timeout=BOOT_TIMEOUT)
        sb_refused = wirecheck(wc, port, wlog, wait=15) != 0
    finally:
        q.stop()
    text = (work / 'boot-tampered.log').read_text(errors='replace')
    facts = boot_facts(text)
    expect(sb_refused and 'Secure boot signature verification failed' in text
           and not facts['measurement'] and not facts['wire'],
           'tampered image, checksum and SHA-256 fixed up: the secure boot v2 signature refused it; '
           'no measurement, no wire')

    # 5: the padding question. The trailer sits between the appended SHA-256
    # and the 4 KB boundary where the signature sector starts, in the span
    # espsecure pads. One byte of it flipped -- a reserved byte, which the gate
    # itself would never look at -- and nothing re-signed must fail secure boot
    # v2, or the RSA signature does not cover the trailer.
    base = (work / 'flash.bin').read_bytes()
    padflip = bytearray(sealed.read_bytes())
    padflip[hashed + 32 + l0_seal.TRAILER_LEN - 1] ^= 0x01
    text, ok = refused(machine, with_app(work, base, app, padflip, 'trailer-flip'), efuse, wc, wlog,
                       work / 'boot-trailer-flip.log', r'tfw-l0: app at 0x[0-9a-f]+ failed verification')
    expect(ok and 'Secure boot signature verification failed' in text,
           'a trailer byte flipped, not re-signed: secure boot v2 refused it -- the span between the '
           'appended SHA-256 and the signature sector is signed; no measurement, no wire')

    # 6: re-signed for secure boot v2, so only layer 0's gate stands in the way.
    unsealed = (idf / 'trusted-firmware.bin').read_bytes()
    image_key = l0_seal.load_p256(out.parent / 'keys' / 'image_key_p256.pem')
    stranger = ec.generate_private_key(ec.SECP256R1())

    def flip(at):
        def tamper(raw):
            raw[at] ^= 0x01
        return tamper

    # The trailer and the envelope are sealed by one call; a case tampers with
    # one of them. The manifest's last byte is inside the COSE payload, so its
    # signature no longer holds while the trailer's still does.
    cases = [
        ('another-board', 0x80, 1, image_key, None, None, ERR_UNSUPPORTED,
         'an image sealed for board 0x80 (esp32p4-poe)'),
        ('another-key', BOARD_ID, 1, stranger, None, None, ERR_CRYPTO,
         'an image signed by an ES256 key the device was not paired with'),
        ('measurement-flip', BOARD_ID, 1, image_key, flip(16), None, ERR_CRYPTO,
         "an image whose trailer measurement is not the image's SHA-256"),
        ('signature-flip', BOARD_ID, 1, image_key, flip(48), None, ERR_CRYPTO,
         'an image with one bit of its ES256 signature flipped'),
        ('manifest-flip', BOARD_ID, 1, image_key, None, flip(-1), ERR_CRYPTO,
         'an image whose SUIT manifest has one byte flipped under a valid trailer'),
    ]
    if anti_rollback:
        # The build stamps one number into both; boot_l0.c refuses two.
        cases.append(('version-mismatch', BOARD_ID, 2, image_key, None, None,
                      ERR_PROTECTED_REGION,
                      'an image of secure_version 1 sealed with trailer version 2'))
    for name, board, version, key, tamper, tamper_envelope, status, what in cases:
        image = work / f'app-{name}.bin'
        l0_seal.seal(unsealed, board, version, key, sign_key, image, suit_emit, tamper,
                     tamper_envelope)
        text, ok = refused(machine, with_app(work, base, app, image.read_bytes(), name), efuse, wc, wlog,
                           work / f'boot-{name}.log', r'tfw-l0: app at 0x[0-9a-f]+ refused by the trailer gate')
        expect(ok and f'refused by the trailer gate (status {status})' in text
               and 'Secure boot signature verification failed' not in text,
               f'{what}, re-signed for secure boot v2: the gate refused it (status {status}); '
               'no measurement, no wire')

    # 7: the OTA session (#48), after the tampered boot: with ota_1 holding a
    # good app, the loader would fall back to it from a tampered ota_0. The
    # app streamed is the sealed one, trailer and SUIT envelope both.
    image = sealed.read_bytes()
    bad = work / 'ota-tampered.bin'
    bad.write_bytes(bytes(flash[app:app + len(image)]))
    parts = partitions(bytes(flash[0x10000:0x10c00]))
    (o0, s0), (o1, _), (od, sd) = parts['ota_0'], parts['ota_1'], parts['otadata']
    before = (work / 'flash.bin').read_bytes()
    olog = work / 'ota.log'
    q, port = boot(machine, work / 'flash.bin', efuse, work / 'boot-4-ota.log')
    try:
        q.wait_for(link)
        expect(wirecheck(wc, port, olog, *attest, *ota(bad),
                         '-ota-fail', str(ERR_CRYPTO)) == 0,
               'boot 4: the tampered app streamed over OTA_BEGIN/DATA is refused at OTA_END '
               '(CRYPTO, the signature); STATUS failed; OTA_ACTIVATE without OTA_AUTH refused',
               logs=(olog, q.logpath))
        expect(wirecheck(wc, port, olog, *attest, *ota(sealed)) == 0,
               f'boot 4: the app ({len(image)} bytes) streamed and accepted at OTA_END; '
               'STATUS complete with every byte; OTA_ACTIVATE without OTA_AUTH refused',
               logs=(olog, q.logpath))
    finally:
        q.stop()
    info = re.findall(r'^ota: slot (\d) state (\d+) version \d+ floor \d+ flags 0x([0-9a-f]{2}) '
                      r'measurement ([0-9a-f]{64})$', olog.read_text(errors='replace'), re.M)
    running = ('0', '2', '00', measurement.hex())        # GOOD, no flags
    expect(info == [running, ('1', '3', '00', '00' * 32), running, ('1', '2', '00', measurement.hex())],
           'OTA_INFO: the running slot good, unflagged and unchanged; the inactive slot failed '
           'after the tampered app, then complete with the app\'s SHA-256')
    after = (work / 'flash.bin').read_bytes()
    expect(after[o1:o1 + len(image)] == image and after[o0:o0 + s0] == before[o0:o0 + s0]
           and after[od:od + sd] == before[od:od + sd],
           'flash: ota_1 holds the streamed app; ota_0 and otadata are as they were')
    q, port = boot(machine, work / 'flash.bin', efuse, work / 'boot-5.log')
    try:
        q.wait_for(link)
        expect(wirecheck(wc, port, wlog, '-tier', str(tier), *attest, '-expect-mark', mark) == 0,
               'boot 5 (cold): the wire, and the EEPROM mark kept')
    finally:
        q.stop()
    text = (work / 'boot-5.log').read_text(errors='replace')
    expect(re.findall(r'tfw-l0: app at 0x([0-9a-f]+) verified, measurement ([0-9a-f]{64})', text)
           == [(f'{o0:x}', measurement.hex())],
           f'boot 5: still ota_0 at 0x{o0:x}, measurement unchanged: nothing activated')

    # 8-10: release 2, what the build makes of ESP_IMAGE_VERSION=2. Each starts
    # from boot 5's flash and eFuses, copied, so none sees another's otadata or
    # floor. OTA_INFO's version is the app's secure_version, which the build
    # stamps only under anti-rollback; the esp32c3's first boot set the floor
    # to ota_0's. On the esp32 the two releases differ in the trailer alone,
    # which the measurement does not cover: there the slot tells them apart.
    rel2 = release(unsealed, 2 if anti_rollback else None, 2, image_key, sign_key, suit_emit,
                   work / 'app-release-2.bin')
    m1, m2 = measurement.hex(), LoadFirmwareImage(machine, str(rel2)).stored_digest.hex()
    v1, v2 = (1, 2) if anti_rollback else (0, 0)
    image_pem = out.parent / 'keys' / 'image_key_p256.pem'
    stranger_pem = work / 'stranger.pem'
    stranger_pem.write_bytes(stranger.private_bytes(serialization.Encoding.PEM,
                                                    serialization.PrivateFormat.PKCS8,
                                                    serialization.NoEncryption()))
    stage = (*attest, *ota(rel2), '-activate', '0', '-reset')
    on_trial = r'tfw-l0: app at 0x[0-9a-f]+ on trial'
    authorized = r'tfw-l0: app at 0x[0-9a-f]+ on trial, activate authorized'

    def verified(path):
        return re.findall(r'tfw-l0: app at 0x([0-9a-f]+) verified, measurement ([0-9a-f]{64})',
                          path.read_text(errors='replace'))

    # 8: an activate the image key did not sign.
    def unauthorized():
        name = 'unauthorized'
        blog, wlog8 = work / f'boot-{name}.log', work / f'ota-{name}.log'
        q, port = boot(machine, copy(work / 'flash.bin', work / f'flash-{name}.bin'),
                       copy(efuse, work / f'efuse-{name}.bin'), blog)
        try:
            q.wait_for(link)
            expect(wirecheck(wc, port, wlog8, *stage, '-auth-key', stranger_pem) == 0,
                   'release 2 streamed; OTA_ACTIVATE after an OTA_AUTH signed by a key the device was not '
                   'paired with: taken, the app holding no key; soft reset', logs=(wlog8, blog))
            q.wait_for(on_trial)
            q.wait_for(link, count=2)
            fell = ota_info(wc, port, work / f'info-{name}-1.log', *attest, '-reset', logs=(blog,))
            q.wait_for(link, count=3)
            again = ota_info(wc, port, work / f'info-{name}-2.log', *attest, logs=(blog,))
        finally:
            q.stop()
        text = blog.read_text(errors='replace')
        expect(f'on trial has no activate authorization (status {ERR_AUTH_REQUIRED})' in text
               and len(re.findall(on_trial, text)) == 1
               and verified(blog) == [(f'{o0:x}', m1)] * 3,
               f'at reset layer 0 refused the trial (AUTH_REQUIRED) and ota_0 ran; the next reset did '
               'not try it again', logs=(blog,))
        want = (STATE_GOOD, v1, v1, FLAG_FELL_BACK, m1)
        expect(fell == want and again == want,
               f'OTA_INFO after each: ota_0 good, version {v1}, floor {v1}, FELL_BACK, its own '
               f'measurement (got {fell}, then {again})')

    # 9: an authorized trial nobody confirms.
    def rollback():
        name = 'rollback'
        blog, wlog9 = work / f'boot-{name}.log', work / f'ota-{name}.log'
        q, port = boot(machine, copy(work / 'flash.bin', work / f'flash-{name}.bin'),
                       copy(efuse, work / f'efuse-{name}.bin'), blog)
        try:
            q.wait_for(link)
            expect(wirecheck(wc, port, wlog9, *stage, '-auth-key', image_pem) == 0,
                   'release 2 streamed; OTA_ACTIVATE after an OTA_AUTH signed by the image key: taken; '
                   'soft reset', logs=(wlog9, blog))
            q.wait_for(authorized)
            q.wait_for(link, count=2)
            trial = ota_info(wc, port, work / f'info-{name}-1.log', *attest, logs=(blog,))
            # The condition is the app's own reset at its deadline, and the boot after.
            q.wait_for(link, count=3, timeout=TRIAL_TIMEOUT + BOOT_TIMEOUT)
            back = ota_info(wc, port, work / f'info-{name}-2.log', *attest, logs=(blog,))
        finally:
            q.stop()
        want = (STATE_TRIAL, v2, v1, FLAG_TRIAL, m2)
        expect(trial == want,
               f'on its trial: OTA_INFO says TRIAL, version {v2}, floor {v1}, release 2\'s measurement '
               f'(got {trial})')
        text = blog.read_text(errors='replace')
        expect(len(re.findall(authorized, text)) == 1
               and verified(blog) == [(f'{o0:x}', m1), (f'{o1:x}', m2), (f'{o0:x}', m1)],
               f'unconfirmed, the trial reset itself within {TRIAL_TIMEOUT}s and ESP-IDF rolled back '
               'to ota_0', logs=(blog,))
        want = (STATE_GOOD, v1, v1, FLAG_FELL_BACK, m1)
        expect(back == want,
               f'after the roll-back: ota_0 good, version {v1}, FELL_BACK, the floor still {v1} '
               f'(got {back})')

    # 10: an authorized trial, confirmed.
    def confirmed():
        name = 'confirmed'
        blog, wlog10 = work / f'boot-{name}.log', work / f'ota-{name}.log'
        flash10, efuse10 = (copy(work / 'flash.bin', work / f'flash-{name}.bin'),
                            copy(efuse, work / f'efuse-{name}.bin'))
        q, port = boot(machine, flash10, efuse10, blog)
        try:
            q.wait_for(link)
            expect(wirecheck(wc, port, wlog10, *stage, '-auth-key', image_pem) == 0,
                   'release 2 streamed and activated, OTA_AUTH signed by the image key; soft reset',
                   logs=(wlog10, blog))
            q.wait_for(authorized)
            q.wait_for(link, count=2)
            kept = ota_info(wc, port, work / f'info-{name}-1.log', *attest,
                            '-confirm', '-signed-image', rel2, '-auth-key', image_pem, logs=(blog,))
        finally:
            q.stop()
        want = (STATE_GOOD, v2, v2, 0, m2)
        expect(kept == want,
               f'OTA_CONFIRM refused without OTA_AUTH, taken after one: release 2 good, unflagged, '
               f'version {v2}, floor {v2} (got {kept})')
        cold_log = work / f'boot-{name}-cold.log'
        q, port = boot(machine, flash10, efuse10, cold_log)
        try:
            q.wait_for(link)
            cold = ota_info(wc, port, work / f'info-{name}-2.log', *attest, logs=(cold_log,))
        finally:
            q.stop()
        expect(cold == want and verified(cold_log) == [(f'{o1:x}', m2)]
               and not re.findall(on_trial, cold_log.read_text(errors='replace')),
               f'cold boot: release 2 from ota_1 at 0x{o1:x}, no trial, the same OTA_INFO', logs=(cold_log,))

    # 8-10 share nothing but their read-only inputs, so they run side by side:
    # each its own QEMU, copies, port and logs, and each streams the whole
    # image. Every round runs to its end, so each stops its own QEMU; then the
    # first failure in round order is raised.
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        rounds = [pool.submit(r) for r in (unauthorized, rollback, confirmed)]
    for r in rounds:
        r.result()

    # 11: the provisioning image, on fresh eFuses and a flash of its own.
    if prov:
        provisioning(prov, machine, sign_key, wc, work, out)
    log('green')


if __name__ == '__main__':
    for sig in (signal.SIGTERM, signal.SIGINT, signal.SIGHUP):
        signal.signal(sig, reap)
    try:
        main()
    except Failure as e:
        log(f'FAILED: {e}')
        sys.exit(1)
