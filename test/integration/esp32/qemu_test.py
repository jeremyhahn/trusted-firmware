"""One ESP32 image in Espressif's QEMU, end to end. Run by `make esp32-qemu-test`.

    qemu_test.py <build-out> <machine> <wirecheck> <suit-emit> [<prov-build-out>]

<build-out> is an `esp32-build` output directory, <machine> esp32c3 or esp32,
<suit-emit> the board's (mk/suit.mk), which l0_seal.py builds the envelope with.
<prov-build-out>, on the esp32c3 only, is the same tier's PROVISION=1 build.
The eFuse image is generated here, into <build-out>/qemu. The secure-boot
signing key is the build's (build/esp32/keys), generated by esp32-build on
first use. Nothing here is committed.

The UDS is NOT secret here: it is the fixed UDS of test/unit/test_deviceid_p256.c
(bytes 0x00..0x1f), so the DeviceID the device derives from it can be checked
against the literal point pinned there, computed by an independent Python
P-256 -- never by the code under test.

What it checks, in order:

  1. Provisioning. QEMU in ROM download mode; espefuse burns the secure-boot
     key digest and SECURE_BOOT_EN, and on the esp32c3 the UDS as an HMAC_UP
     key in KEY1. Nothing else: the hmac-p256 tier derives its DeviceID from
     the UDS, so no DS key and no flash record.
  2. Boot 1. Secure boot v2 verifies the bootloader in ROM and the app in the
     bootloader; layer 0 logs a measurement equal to the image's own SHA-256;
     layer 0's ES256 gate passes trailer v1 against the board id, the eFuse
     floor, the image key pinned in tfw_plat and the signature, and the SUIT
     manifest after it against the image's digest and size, the board's
     class and the trailer's image_version -- the sealed image boots;
     the app logs the CDI's and DeviceID's fingerprints, the CDI's equal to
     the value computed here from the UDS and the DeviceID's to SHA-256 of the
     pinned point; the Go SDK answers over Ethernet -- CAPS, and ATTEST as
     CAPS's tier says: on the esp32c3 ES256 evidence that crypto/ecdsa
     verifies under the pinned point, on the esp32 (none tier) a refusal --
     writes an EEPROM mark and soft-resets the device.
  3. Boot 2 (the soft reset) and boot 3 (a cold start of a new QEMU on the
     same flash and eFuses): the same measurement, CDI and DeviceID, and the
     mark still there.
  4. A tampered image -- one byte of the app flipped -- is refused: no
     measurement, no wire.
  5. One byte of the trailer flipped and nothing re-signed: secure boot v2
     refuses it, so the span between the appended SHA-256 and the signature
     sector is under the RSA signature (the design's padding question).
  6. Images re-signed for secure boot v2 that layer 0's gate must refuse: for
     another board, signed by an ES256 key the device was not paired with, a
     measurement flipped, the ES256 signature flipped, a SUIT manifest byte
     flipped under a valid trailer; under anti-rollback (the esp32c3), a
     trailer version other than the image's secure_version. No
     measurement, no wire.
  7. The OTA session on esp_ota (#48). Boot 4 streams the tampered app of 4
     over OTA_BEGIN/DATA/END, and OTA_END refuses it on its signature (CRYPTO,
     STATUS failed); then it streams the app itself, which OTA_END takes:
     STATUS complete, and OTA_INFO gives the inactive slot the image's own
     SHA-256. OTA_ACTIVATE without OTA_AUTH is refused (AUTH_REQUIRED). With
     QEMU stopped the flash shows ota_1 holding the app and ota_0 and otadata
     as they were; boot 5 still runs ota_0, with the same measurement.
  8. Release 2 -- the app with secure_version 2 under anti-rollback, sealed
     with trailer version 2 -- activated with OTA_AUTH signed by a key the
     device was not paired with. The app takes it (it does not hold the key);
     at reset layer 0 refuses the trial (no activate authorization) and ota_0
     runs, OTA_INFO flagging the fall-back; the next reset aborts the entry and
     the trial is never tried again.
  9. Release 2 activated with OTA_AUTH signed by the image key: layer 0 runs
     the trial, OTA_INFO says TRIAL with release 2's measurement, and nothing
     confirms it. At the trial deadline the app resets by itself and ESP-IDF
     rolls back to ota_0; the floor is where it was.
 10. Release 2 activated and confirmed (OTA_CONFIRM, ES256 signed): OTA_INFO
     gives it good, unflagged, with secure version 2 -- and on the esp32c3 the
     eFuse floor raised to 2 by ESP-IDF's mark-valid, in QEMU's file-backed
     eFuses only. A cold boot runs it from ota_1 with no trial.
 11. With <prov-build-out>: the provisioning image (esp32-p4-design.md
     section 2.4) on fresh eFuses with secure boot and no UDS. PROV_GENKEY
     returns a P-256 point and the part logs the burn; PROV_PUBKEY agrees; a
     second PROV_GENKEY is refused. Back in download mode the ROM is in Secure
     Download Mode and espefuse cannot read the eFuses at all. Read offline
     from QEMU's eFuse file after it exits, there is one HMAC_UP key, its
     read-protect bit set, it and its purpose write-protected, and it derives
     the point. A normal boot on those eFuses then logs the DeviceID of that
     point and ATTEST verifies under it. This UDS came from the part's noise
     source, so the point is checked against what the device returned, not a
     literal.

The serial logs are left in <build-out>/qemu for the reader.
"""

