"""One ESP32 image in Espressif's QEMU, end to end. Run by `make esp32-qemu-test`.

    qemu_test.py <build-out> <machine> <wirecheck>

<build-out> is an `esp32-build` output directory, <machine> esp32c3 or esp32.
Everything secret is generated here, into <build-out>/qemu, and never leaves
it: the eFuse image, the UDS and DS keys, and the DeviceID's RSA key. The
secure-boot signing key is the build's (build/esp32/keys), generated by
esp32-build on first use. Nothing here is committed.

What it checks, in order:

  1. Provisioning. QEMU in ROM download mode; espefuse burns the secure-boot
     key digest and SECURE_BOOT_EN, and on the esp32c3 the UDS as an HMAC_UP
     key in KEY1 and the DS key as HMAC_DOWN_DIGITAL_SIGNATURE in KEY2. The
     DeviceID record (esp_secure_cert's DS encoding) goes into tfw_id.
  2. Boot 1. Secure boot v2 verifies the bootloader in ROM and the app in the
     bootloader; layer 0 logs a measurement equal to the image's own SHA-256;
     the app logs the CDI's and DeviceID's fingerprints, both equal to the
     values computed here from the keys; the Go SDK answers over Ethernet,
     writes an EEPROM mark and soft-resets the device.
  3. Boot 2 (the soft reset) and boot 3 (a cold start of a new QEMU on the
     same flash and eFuses): the same measurement, CDI and DeviceID, and the
     mark still there.
  4. A tampered image -- one byte of the app flipped -- is refused: no
     measurement, no wire.

The serial logs are left in <build-out>/qemu for the reader.
"""

import hashlib
import hmac
import os
import re
import shutil
import socket
import struct
import subprocess
import sys
import time
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

sys.path.insert(0, os.path.join(os.environ['IDF_PATH'], 'tools'))
from idf_py_actions.qemu_ext import QEMU_TARGETS  # noqa: E402  Espressif's eFuse defaults
from esptool.bin_image import LoadFirmwareImage  # noqa: E402
from esp_secure_cert.configure_ds import calculate_rsa_ds_params  # noqa: E402

FLASH_SIZE = 4 * 1024 * 1024
WIRE_PORT = 21574              # TFW_ESP_WIRE_PORT, src/hal/esp32/hal_esp32.h
BOARD_ID = 0x81                # boards/esp32-qemu/board_profile.h
TIER_NONE = 0
TIER_SECURE_ELEMENT = 2        # TFW_CRYPTO_SECURE_ELEMENT, include/tfw/types.h
BOOT_TIMEOUT = 90

# src/hal/esp32/id_record.h
ID_MAGIC = 0x44494654
ID_VERSION = 1
ID_MAX_BYTES = 512
ID_C_MAX = 1584
DS_KEY_BLOCK = 2               # eFuse BLOCK_KEY2

MACHINES = {
    'esp32c3': {'bootloader': 0x0, 'identity': True, 'rsa_bits': 3072},
    'esp32': {'bootloader': 0x1000, 'identity': False},
}


class Failure(Exception):
    pass


def log(msg):
    print(f'esp32-qemu-test: {msg}', flush=True)


def free_port():
    with socket.socket() as s:
        s.bind(('127.0.0.1', 0))
        return s.getsockname()[1]


def qemu_base(machine, flash, efuse):
    t = QEMU_TARGETS[machine]
    args = [t.qemu_prog] + t.qemu_args.split()
    if flash is not None:
        args += ['-drive', f'file={flash},if=mtd,format=raw']
    return args + [
        '-drive', f'file={efuse},if=none,format=raw,id=efuse',
        '-global', f'driver=nvram.{machine}.efuse,property=drive,value=efuse',
        '-global', f'driver=timer.{machine}.timg,property=wdt_disable,value=true',
        '-nographic',
    ]


class Qemu:
    """One QEMU process, its serial console appended to a log file."""

    def __init__(self, args, logpath):
        self.logpath = logpath
        self.logfile = open(logpath, 'ab')
        self.proc = subprocess.Popen(args, stdin=subprocess.DEVNULL,
                                     stdout=self.logfile, stderr=subprocess.STDOUT)

    def text(self):
        return Path(self.logpath).read_text(errors='replace')

    def wait_for(self, pattern, count=1, timeout=BOOT_TIMEOUT):
        deadline = time.time() + timeout
        while time.time() < deadline:
            if len(re.findall(pattern, self.text())) >= count:
                return
            # Between reads of the log, wait on the one other thing that can
            # happen: QEMU exiting.
            try:
                self.proc.wait(min(0.25, max(0, deadline - time.time())))
            except subprocess.TimeoutExpired:
                continue
            raise Failure(f'QEMU exited ({self.proc.returncode}) waiting for {pattern!r}')
        raise Failure(f'{timeout}s without {pattern!r} (x{count}) in {self.logpath}')

    def stop(self):
        if self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(10)
            except subprocess.TimeoutExpired:
                self.proc.kill()
                self.proc.wait()
        self.logfile.close()


def run(args, logpath, **kw):
    with open(logpath, 'ab') as f:
        f.write(f'$ {" ".join(map(str, args))}\n'.encode())
        f.flush()
        r = subprocess.run(list(map(str, args)), stdout=f, stderr=subprocess.STDOUT, **kw)
    return r.returncode


# --------------------------------------------------------------- the keys

def make_identity(work, machine):
    """The UDS, the DS key and the DeviceID, with the values the device must log."""
    bits = MACHINES[machine]['rsa_bits']
    uds = os.urandom(32)
    ds_key = os.urandom(32)
    (work / 'uds.bin').write_bytes(uds)
    (work / 'ds_key.bin').write_bytes(ds_key)
    key = rsa.generate_private_key(public_exponent=65537, key_size=bits)
    pem = work / 'deviceid.pem'
    pem.write_bytes(key.private_bytes(serialization.Encoding.PEM,
                                      serialization.PrivateFormat.PKCS8,
                                      serialization.NoEncryption()))
    c, iv, key_bits = calculate_rsa_ds_params(str(pem), None, ds_key, machine)
    if key_bits != bits or len(c) > ID_C_MAX:
        raise Failure(f'DS parameters: {key_bits} bits, {len(c)} bytes of ciphertext')
    pub = key.public_key().public_numbers()
    n_be = pub.n.to_bytes(bits // 8, 'big')
    record = (struct.pack('<IBBHI', ID_MAGIC, ID_VERSION, DS_KEY_BLOCK, bits, pub.e)
              + n_be[::-1].ljust(ID_MAX_BYTES, b'\0')
              + iv
              + c.ljust(ID_C_MAX, b'\0'))
    assert len(record) == 12 + ID_MAX_BYTES + 16 + ID_C_MAX
    fp = hashlib.sha256(n_be + pub.e.to_bytes(4, 'big')).hexdigest()[:32]
    return uds, record, f'rsa{bits}', fp


def cdi_fingerprint(uds, measurement):
    """What the app logs: HMAC(CDI, label) of CDI = HMAC-SHA256(UDS, measurement)."""
    cdi = hmac.new(uds, measurement, hashlib.sha256).digest()
    return hmac.new(cdi, b'tfw-cdi-fingerprint-v1', hashlib.sha256).hexdigest()[:32]


# -------------------------------------------------------------- the flash

def partitions(table):
    """label -> (offset, size) from an ESP-IDF binary partition table."""
    out = {}
    for i in range(0, len(table), 32):
        e = table[i:i + 32]
        if e[:2] != b'\xaa\x50':
            break
        _, _, _, off, size, label, _ = struct.unpack('<2sBBII16sI', e)
        out[label.rstrip(b'\0').decode()] = (off, size)
    return out


def make_flash(idf, machine, record, path):
    flash = bytearray(b'\xff' * FLASH_SIZE)

    def place(off, data):
        flash[off:off + len(data)] = data

    place(MACHINES[machine]['bootloader'], (idf / 'bootloader' / 'bootloader.bin').read_bytes())
    table = (idf / 'partition_table' / 'partition-table.bin').read_bytes()
    place(0x10000, table)
    parts = partitions(table)
    place(parts['otadata'][0], (idf / 'ota_data_initial.bin').read_bytes())
    place(parts['ota_0'][0], (idf / 'trusted-firmware.bin').read_bytes())
    if record is not None:
        place(parts['tfw_id'][0], record)
    path.write_bytes(flash)
    return parts


# --------------------------------------------------------------- the eFuses

def provision_efuses(work, machine, sign_key, logpath):
    efuse = work / 'efuse.bin'
    efuse.write_bytes(QEMU_TARGETS[machine].default_efuse)
    port = free_port()
    args = qemu_base(machine, None, efuse) + QEMU_TARGETS[machine].boot_mode_arg.split() + [
        '-serial', f'tcp:127.0.0.1:{port},server,nowait']
    q = Qemu(args, logpath)
    try:
        deadline = time.time() + 20
        while True:
            try:
                socket.create_connection(('127.0.0.1', port), 1).close()
                break
            except OSError:
                if time.time() > deadline:
                    raise Failure('QEMU download mode never opened its serial port')
                try:
                    q.proc.wait(0.2)
                except subprocess.TimeoutExpired:
                    continue
                raise Failure(f'QEMU exited ({q.proc.returncode}) before opening its serial port')
        espefuse = ['espefuse.py', '--chip', machine, '--port', f'socket://127.0.0.1:{port}',
                    '--before', 'no_reset', '--do-not-confirm']
        if machine == 'esp32':
            burn = ['burn_key_digest', sign_key, 'burn_efuse', 'ABS_DONE_1', '1']
        else:
            burn = ['burn_key_digest', 'BLOCK_KEY0', sign_key, 'SECURE_BOOT_DIGEST0',
                    'burn_key',
                    'BLOCK_KEY1', work / 'uds.bin', 'HMAC_UP',
                    'BLOCK_KEY2', work / 'ds_key.bin', 'HMAC_DOWN_DIGITAL_SIGNATURE',
                    'burn_efuse', 'SECURE_BOOT_EN', '1']
        if run(espefuse + burn, logpath) != 0:
            raise Failure(f'espefuse refused the burn, see {logpath}')
        summary = work / 'efuse-summary.txt'
        if run(espefuse + ['summary'], summary) != 0:
            raise Failure(f'espefuse summary failed, see {summary}')
        flag = 'ABS_DONE_1' if machine == 'esp32' else 'SECURE_BOOT_EN'
        if not re.search(rf'^{flag} .*= True', summary.read_text(), re.M):
            raise Failure(f'{flag} is not set after the burn, see {summary}')
    finally:
        q.stop()
    return efuse


# ----------------------------------------------------------------- a boot

def boot(machine, flash, efuse, logpath):
    port = free_port()
    args = qemu_base(machine, flash, efuse) + [
        '-nic', f'user,model=open_eth,hostfwd=tcp:127.0.0.1:{port}-:{WIRE_PORT}']
    return Qemu(args, logpath), port


def wirecheck(binary, port, logpath, *extra, wait=BOOT_TIMEOUT):
    return run([binary, '-addr', f'127.0.0.1:{port}', '-wait', f'{wait}s',
                '-board', str(BOARD_ID)] + list(extra), logpath)


def boot_facts(text):
    """The per-boot lines, in boot order."""
    return {
        'measurement': re.findall(r'tfw-l0: app at 0x[0-9a-f]+ verified, measurement ([0-9a-f]{64})', text),
        'cdi': re.findall(r'tfw-id: cdi hmac-fingerprint=([0-9a-f]{32})', text),
        'deviceid': re.findall(r'tfw-id: deviceid (rsa\d+) sha256\(n\|\|e\)=([0-9a-f]{32}) ds-selftest=ok', text),
        'wire': re.findall(r'tfw-eth: link up, address \S+, wire on tcp/(\d+)', text),
    }


def expect(cond, what):
    if not cond:
        raise Failure(what)
    log(f'  ok  {what}')


def main():
    out, machine, wc = Path(sys.argv[1]).resolve(), sys.argv[2], Path(sys.argv[3]).resolve()
    if machine not in MACHINES:
        raise Failure(f'machine {machine}: not one of {", ".join(MACHINES)}')
    identity = MACHINES[machine]['identity']
    idf = out / 'idf'
    sign_key = (out.parent / 'keys' / 'secure_boot_signing_key.pem').resolve()
    work = out / 'qemu'
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    log(f'{machine}: {out.name}, logs in {work}')

    measurement = LoadFirmwareImage(machine, str(idf / 'trusted-firmware.bin')).stored_digest
    uds = record = None
    if identity:
        uds, record, id_alg, id_fp = make_identity(work, machine)
    make_flash(idf, machine, record, work / 'flash.bin')
    efuse = provision_efuses(work, machine, sign_key, work / 'provision.log')
    log('  ok  eFuses burned: secure boot v2 key digest and enable'
        + (', UDS (HMAC_UP), DS key (HMAC_DOWN_DIGITAL_SIGNATURE)' if identity else ''))

    tier = TIER_SECURE_ELEMENT if identity else TIER_NONE
    mark = 'tfw-' + os.urandom(2).hex()      # EEPROM_WRITE takes up to 8 bytes
    wlog = work / 'wirecheck.log'

    # Boot 1, then the soft reset it ends with: boot 2 in the same QEMU.
    q, port = boot(machine, work / 'flash.bin', efuse, work / 'boot-1-2.log')
    try:
        q.wait_for(r'tfw-eth: link up')
        expect(wirecheck(wc, port, wlog, '-tier', str(tier), '-mark', mark, '-reset') == 0,
               'boot 1: PING, CAPS (board 0x81, tier %d), SYSINFO over Ethernet; mark written; soft reset' % tier)
        q.wait_for(r'tfw-eth: link up', count=2)
        expect(wirecheck(wc, port, wlog, '-tier', str(tier), '-expect-mark', mark) == 0,
               'boot 2 (soft reset): the wire, and the EEPROM mark kept')
    finally:
        q.stop()
    # Boot 3: a new QEMU on the same flash and eFuses.
    q, port = boot(machine, work / 'flash.bin', efuse, work / 'boot-3.log')
    try:
        q.wait_for(r'tfw-eth: link up')
        expect(wirecheck(wc, port, wlog, '-tier', str(tier), '-expect-mark', mark) == 0,
               'boot 3 (cold): the wire, and the EEPROM mark kept')
    finally:
        q.stop()

    text = (work / 'boot-1-2.log').read_text(errors='replace') + (work / 'boot-3.log').read_text(errors='replace')
    facts = boot_facts(text)
    expect(facts['measurement'] == [measurement.hex()] * 3,
           f'3 boots: secure boot v2 verified the app; measurement {measurement.hex()[:16]}... is the image SHA-256')
    if identity:
        want_cdi = cdi_fingerprint(uds, measurement)
        expect(facts['cdi'] == [want_cdi] * 3,
               f'3 boots: CDI fingerprint {want_cdi}, HMAC_UP over the measurement, same every boot')
        expect(facts['deviceid'] == [(id_alg, id_fp)] * 3,
               f'3 boots: DeviceID {id_alg} {id_fp}, DS self-test verified, same every boot')
    else:
        expect(not facts['cdi'],
               'no CDI on a part with no HMAC peripheral (none tier)')

    # A tampered image, tampered the way an attacker would: one byte of code
    # flipped, and the image's checksum and appended SHA-256 both fixed up to
    # match, so the only thing left to notice is the RSA signature.
    tampered = work / 'flash-tampered.bin'
    flash = bytearray((work / 'flash.bin').read_bytes())
    app = partitions(bytes(flash[0x10000:0x10c00]))['ota_0'][0]
    hashed = LoadFirmwareImage(machine, str(idf / 'trusted-firmware.bin')).data_length
    flash[app + 0x1000] ^= 0x01                  # inside segment 0's data
    flash[app + hashed - 1] ^= 0x01              # the XOR checksum, last byte before the digest
    flash[app + hashed:app + hashed + 32] = hashlib.sha256(flash[app:app + hashed]).digest()
    tampered.write_bytes(flash)
    q, port = boot(machine, tampered, efuse, work / 'boot-tampered.log')
    try:
        q.wait_for(r'tfw-l0: app at 0x[0-9a-f]+ failed verification', timeout=BOOT_TIMEOUT)
        refused = wirecheck(wc, port, wlog, wait=15) != 0
    finally:
        q.stop()
    text = (work / 'boot-tampered.log').read_text(errors='replace')
    facts = boot_facts(text)
    expect(refused and 'Secure boot signature verification failed' in text
           and not facts['measurement'] and not facts['wire'],
           'tampered image, checksum and SHA-256 fixed up: the secure boot v2 signature refused it; '
           'no measurement, no wire')
    log(f'{machine}: green')


if __name__ == '__main__':
    try:
        main()
    except Failure as e:
        log(f'FAILED: {e}')
        sys.exit(1)
