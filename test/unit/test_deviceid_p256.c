/*
 * The P-256 DeviceID derivation (src/crypto/deviceid_p256.c), pinned against
 * facts that do not come from this repository.
 *
 * Signing is checked against RFC 6979 A.2.5 (P-256, SHA-256, "sample" and
 * "test"), byte for byte. Every other literal -- the seed of a fixed UDS, its
 * scalar and point, the retried scalars, the signatures -- was computed with an
 * independent pure-Python P-256 and RFC 6979 (affine arithmetic over SEC 2's
 * domain parameters, Python's hmac and hashlib) that reproduces A.2.5 first,
 * and was written down before this suite ran. A literal that moves is a
 * DeviceID that moved on every enrolled device: not a test to update.
 *
 * The suite links its own tfw_secure_zero, in place of src/core/secure_zero.c,
 * which keeps a copy of what it is asked to zero. That is how it sees the
 * scalar handed to it: the derivation's stack is gone when the call returns.
 */
#include <string.h>
#include "unity.h"
#include "uECC.h"
#include "sha256.h"
#include "deviceid_p256.h"

/* ---------------------------------------------------- the zeroing recorder */

#define ZERO_MAX  8u
#define ZERO_COPY 128u

static unsigned zero_calls;
static size_t   zero_len[ZERO_MAX];
static uint8_t  zero_before[ZERO_MAX][ZERO_COPY];
static int      zero_after_ok[ZERO_MAX];

void tfw_secure_zero(void *p, size_t n)
{
    volatile uint8_t *v = (volatile uint8_t *)p;
    size_t            i;
    int               ok = 1;

    if (zero_calls < ZERO_MAX) {
        zero_len[zero_calls] = n;
        memcpy(zero_before[zero_calls], p, n < ZERO_COPY ? n : ZERO_COPY);
    }
    for (i = 0; i < n; i++) { v[i] = 0u; }
    for (i = 0; i < n; i++) { ok = ok && v[i] == 0u; }
    if (zero_calls < ZERO_MAX) {
        zero_after_ok[zero_calls] = ok;
    }
    zero_calls++;
}

void setUp(void)
{
    zero_calls = 0u;
    memset(zero_len, 0, sizeof zero_len);
    memset(zero_before, 0, sizeof zero_before);
    memset(zero_after_ok, 0, sizeof zero_after_ok);
}
void tearDown(void) { uECC_set_rng(0); }

