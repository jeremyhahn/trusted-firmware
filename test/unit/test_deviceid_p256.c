static void test_the_seed_signs_the_pinned_es256_signature_and_it_verifies(void)
{
    uint8_t h[32], sig[64], again[64];

    sha("tfw-deviceid-selftest-v1", h);
    TEST_ASSERT_EQUAL_UINT8_ARRAY(DIGEST, h, 32);
    tfw_deviceid_p256_sign(SEED, DIGEST, sig);
    TEST_ASSERT_EQUAL_UINT8_ARRAY(SEED_SIG, sig, 64);
    TEST_ASSERT_TRUE(verifies(SEED_PUB, DIGEST, sig));
    /* Deterministic: no entropy, the same bytes every time. */
    tfw_deviceid_p256_sign(SEED, DIGEST, again);
    TEST_ASSERT_EQUAL_UINT8_ARRAY(sig, again, 64);
}

